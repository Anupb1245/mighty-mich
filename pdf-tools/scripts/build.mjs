// Assemble dist/ with just what a static host needs. `npm run build`.
// Also generates clean-URL rewrites (Netlify, Vercel), a sitemap and robots.txt from the tool catalog.
import { cpSync, mkdirSync, rmSync, writeFileSync, existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "dist");
const SITE_URL = process.env.SITE_URL || ""; // e.g. https://example.com — used for the sitemap

if (!existsSync(join(root, "vendor", "pdf-lib.esm.js"))) {
  console.error("build: vendor/ is missing — run npm install first");
  process.exit(1);
}

// Tool ids from the registry itself (the catalog modules are safe to import under Node);
// fall back to scanning the sources if a browser-only import ever sneaks in.
let ids = [];
try {
  const { TOOLS } = await import(pathToFileURL(join(root, "src/registry.js")).href);
  ids = TOOLS.filter((t) => !t.hidden).map((t) => t.id);
} catch (err) {
  console.warn("build: registry import failed, scanning sources:", String(err?.message || err).slice(0, 80));
  for (const f of readdirSync(join(root, "src/catalog")).filter((f) => f.endsWith(".js"))) {
    const src = readFileSync(join(root, "src/catalog", f), "utf8");
    for (const m of src.matchAll(/^\s*id:\s*"([a-z0-9-]+)",?\s*$/gm)) ids.push(m[1]);
  }
}
const unique = [...new Set(ids)];

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const items = ["index.html", "tools.html", "tool.html", "404.html", "styles.css", "favicon.svg", "src", "vendor"];
for (const item of items) cpSync(join(root, item), join(out, item), { recursive: true });

// GitHub Pages: skip Jekyll so files like _redirects and the vendor .mjs are served as-is.
writeFileSync(join(out, ".nojekyll"), "");

// Netlify
writeFileSync(join(out, "_redirects"), ["# generated by scripts/build.mjs", "/tools   /tools.html   200", ...unique.map((id) => `/${id}   /tool.html?tool=${id}   200`), ""].join("\n"));

// Vercel
writeFileSync(
  join(out, "vercel.json"),
  JSON.stringify(
    {
      rewrites: [
        { source: "/tools", destination: "/tools.html" },
        { source: `/:tool(${unique.join("|")})`, destination: "/tool.html?tool=:tool" },
      ],
      headers: [
        {
          source: "/(.*)",
          headers: [
            { key: "X-Content-Type-Options", value: "nosniff" },
            { key: "Referrer-Policy", value: "no-referrer" },
            { key: "Content-Security-Policy", value: "default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; worker-src 'self' blob:; connect-src *; object-src 'none'" },
          ],
        },
      ],
    },
    null,
    2
  )
);

// robots + sitemap (sitemap only when SITE_URL is known)
writeFileSync(join(out, "robots.txt"), `User-agent: *\nAllow: /\n${SITE_URL ? `Sitemap: ${SITE_URL.replace(/\/$/, "")}/sitemap.xml\n` : ""}`);
if (SITE_URL) {
  const base = SITE_URL.replace(/\/$/, "");
  const urls = ["", "tools.html", ...unique.map((id) => `tool.html?tool=${id}`)].map((p) => `  <url><loc>${base}/${p.replace(/&/g, "&amp;")}</loc></url>`);
  writeFileSync(join(out, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`);
}

console.log(`build: ${items.length} entries copied to dist/, ${unique.length} tool routes generated`);
